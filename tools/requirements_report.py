'''Requirements = tests, put together: the catalog (written by tests/test_requirements.py), the evidence of the last test
run, the post-deploy checks on the real car and Frank's learning sessions. Writes project/generated/REQUIREMENTS.md (with the spoken wishes as section W) and
<voice dir>/requirements_status.json (for Claude voice), and returns the gaps:
  missing   a requirement checked "auto" without a passing test: tools/run_tests.py fails
  unknown   evidence for an id that is not in the catalog (a typo, or a requirement that was removed): fails too
Usage: python tools/requirements_report.py   (after tools/run_tests.py)'''
import collections
import json
import os
import sys

import pc_settings
import wish_list
from remote_control import requirements

CATALOG_FILE = os.path.join(pc_settings.VOICE_DIR, 'requirements_catalog.json')
COVERAGE_FILE = os.path.join(pc_settings.VOICE_DIR, 'coverage.jsonl')
REAL_CAR_FILE = os.path.join(pc_settings.VOICE_DIR, 'real_car_results.jsonl')    # tools/deploy_check.py
OWNER_VOICE_FILE = os.path.join(pc_settings.VOICE_DIR, 'recordings', 'results.jsonl')  # learning sessions, copied from the car
STATUS_FILE = os.path.join(pc_settings.VOICE_DIR, 'requirements_status.json')
MARKDOWN_FILE = os.path.join(pc_settings.REPO, 'project', 'generated', 'REQUIREMENTS.md')
LEVELS = {'S': 'System', 'V': 'Voice commands', 'K': 'Dashboard and web (click)', 'C': 'Claude'}
MARK = {'auto': 'A', 'real car': 'R', 'your voice': 'Y', 'manual': 'M'}


def _lines(path):
    if not os.path.isfile(path):
        return []
    with open(path, encoding='utf-8') as lines:
        return [json.loads(line) for line in lines if line.strip()]


def _owner_voice():
    '''Learning tries the car understood, as voice requirement evidence.'''
    shown = []
    for result in _lines(OWNER_VOICE_FILE):
        if result.get('verdict') == 'understood' and result['phrase'] in requirements.vocabulary.phrases(result['language']):
            requirement_id, variant = requirements.voice_requirement(result['language'], result['phrase'])
            shown.append({'id': requirement_id, 'variant': variant, 'evidence': 'your voice', 'when': result.get('time', '')})
    return shown


def build():
    '''Returns (status rows, missing, unknown) and writes the two status files.'''
    with open(CATALOG_FILE, encoding='utf-8') as saved:
        catalog = json.load(saved)
    known = {row['id']: row for row in catalog}
    shown = collections.defaultdict(dict)        # (id, variant) -> {evidence: when}
    unknown = set()
    for item in _lines(COVERAGE_FILE) + _lines(REAL_CAR_FILE) + _owner_voice():
        if item['id'] not in known or item['variant'] not in known[item['id']]['variants']:
            unknown.add('%s / %s' % (item['id'], item['variant']))
            continue
        shown[(item['id'], item['variant'])][item['evidence']] = item.get('when', 'last test run')
    rows, missing = [], []
    for row in catalog:
        variants = [{'variant': variant, 'shown': shown.get((row['id'], variant), {})} for variant in row['variants']]
        done = sum(1 for variant in variants if row['checked_by'] in variant['shown'])
        state = 'ok' if done == len(variants) else ('partial' if done else 'open')
        if row['checked_by'] == 'auto' and state != 'ok':
            missing.append('%s (%d of %d variants)' % (row['id'], done, len(variants)))
        rows.append(dict(row, state=state, variants=variants))
    with open(STATUS_FILE, 'w', encoding='utf-8') as status:
        json.dump(rows, status, ensure_ascii=False, indent=1)
    _write_markdown(rows, sorted(unknown))
    return rows, missing, sorted(unknown)


def _write_markdown(rows, unknown):
    counts = collections.Counter(row['state'] for row in rows)
    lines = ['# PiCar requirements = tests', '',
             'Generated by tools/requirements_report.py (not in git). Evidence per variant: A automatic test, R real car (post-deploy check),',
             'Y your voice (learning session), M by hand. "checked by" says which one a requirement needs.', '',
             '**%d requirements: %d ok, %d partial, %d open.**' % (len(rows), counts['ok'], counts['partial'], counts['open'])]
    if unknown:
        lines += ['', '**Evidence for unknown ids:** ' + ', '.join(unknown)]
    lines += ['', wish_list.WishList(pc_settings.WISHES_DIR).markdown().rstrip('\n')]  # first: what Frank asked for
    for level, level_name in LEVELS.items():
        level_rows = [row for row in rows if row['id'].startswith(level + '.')]
        categories = collections.OrderedDict((row['id'].split('.')[1], None) for row in level_rows)
        lines += ['', '## %s %s' % (level, level_name)]
        for category in categories:
            lines += ['', '### %s' % category, '', '| id | requirement | checked by | state | variants |', '|---|---|---|---|---|']
            for row in (row for row in level_rows if row['id'].split('.')[1] == category):
                variants = ', '.join('%s %s' % (variant['variant'], ''.join(MARK[evidence] for evidence in requirements.EVIDENCE if evidence in variant['shown']) or '–')
                                     for variant in row['variants'])
                lines.append('| %s | %s | %s | %s | %s |' % (row['id'], row['title'], row['checked_by'], row['state'], variants))
    os.makedirs(os.path.dirname(MARKDOWN_FILE), exist_ok=True)
    with open(MARKDOWN_FILE, 'w', encoding='utf-8') as markdown:
        markdown.write('\n'.join(lines) + '\n')


def rebuild_if_possible():
    '''After a wish step: REQUIREMENTS.md again, once tools/run_tests.py has written the catalog.'''
    if os.path.isfile(CATALOG_FILE):
        build()


def summary(rows=None):
    '''A few sentences for Claude voice and the chat: counts and what is still open, by level.'''
    if rows is None:
        try:
            with open(STATUS_FILE, encoding='utf-8') as status:
                rows = json.load(status)
        except (OSError, ValueError):
            return 'No requirements report yet (tools/run_tests.py makes it).'
    counts = collections.Counter(row['state'] for row in rows)
    open_rows = [row for row in rows if row['state'] != 'ok']
    by_level = collections.Counter(LEVELS[row['id'][0]] for row in open_rows)
    return ('%d requirements, %d fully shown. Not fully shown: %s. Examples: %s.'
            % (len(rows), counts['ok'], ', '.join('%s %d' % item for item in by_level.items()) or 'none',
               '; '.join('%s (%s, needs %s)' % (row['title'], row['state'], row['checked_by']) for row in open_rows[:6]) or 'none'))


if __name__ == '__main__':
    report_rows, report_missing, report_unknown = build()
    print(summary(report_rows))
    print('missing automatic tests:', report_missing or 'none')
    print('unknown evidence:', report_unknown or 'none')
    sys.exit(1 if report_missing or report_unknown else 0)
